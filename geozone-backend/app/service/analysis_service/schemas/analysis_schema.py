ParcelIdStr = Annotated[str, Field(pattern=r"^\d{3}\.\d{2}-\d{2}-\d{2}(?:\.\d+)?$")]


class AnalysisRequest(BaseModel):
    pid: ParcelIdStr
    address: str
    zone_code: str
    land_desc: str
    land_sf:str

# ---------- Computed facts (never written by the LLM) ----------

class RezoningInfo(BaseModel):
    ordinance_number: int
    adopted_date: date | None = None
    from_zone: str | None = None
    to_zone: str | None = None
    has_proffer: bool = False


class OverlayMatch(BaseModel):
    layer: Literal["height", "historic", "parking", "paid_parking"]
    name: str | None = None
    overlap_pct: float | None = Field(None, ge=0, le=100)  # share of parcel covered


class ParcelFacts(BaseModel):
    parcel_id: int
    address: str | None = None
    zone_code: str | None = None
    zone_description: str | None = None
    lot_area_sqft: float | None = None
    overlays: list[OverlayMatch] = []
    rezoning: RezoningInfo | None = None


class Flag(BaseModel):
    """Deterministic warnings generated by your code, not the model."""
    code: Literal["PROFFER", "CDD", "HISTORIC_DISTRICT", "MULTI_DISTRICT", "NO_ORDINANCE_TEXT"]
    severity: Literal["info", "warning"]
    message: str


# ---------- LLM-generated content ----------

class Citation(BaseModel):
    id: str                      # e.g. "c1", referenced from claims
    section: str                 # ordinance section number, e.g. "3-306"
    title: str | None = None
    url: str | None = None


class UseGroups(BaseModel):
    permitted: list[str] = []
    conditional: list[str] = []   # special use permit required
    prohibited: list[str] = []


class Standard(BaseModel):
    label: str                    # "Maximum height"
    value: str                    # "35 ft"   (display string)
    explanation: str              # what it means for this lot
    citation_ids: list[str] = []


class Constraint(BaseModel):
    title: str
    detail: str
    citation_ids: list[str] = []


class NextStep(BaseModel):
    action: str
    reason: str | None = None


class AnalysisContent(BaseModel):
    """This is the schema you ask the LLM to return, and nothing else."""
    summary: str
    uses: UseGroups
    development_standards: list[Standard] = []
    constraints: list[Constraint] = []
    next_steps: list[NextStep] = []
    open_questions: list[str] = []          # things the model could not determine
    citations: list[Citation] = []
    confidence: Literal["high", "medium", "low"]


# ---------- Metadata ----------

class DataFreshness(BaseModel):
    dataset: str
    source_updated_at: datetime | None = None


class AnalysisMeta(BaseModel):
    cached: bool
    generated_at: datetime
    persona: Persona
    model: str
    prompt_version: str
    ordinance_version: str
    data_freshness: list[DataFreshness] = []


# ---------- Envelope returned to the client ----------

class AnalysisResponse(BaseModel):
    status: Literal["ok", "partial", "insufficient_data"]
    facts: ParcelFacts
    flags: list[Flag] = []
    analysis: AnalysisContent | None = None   # None when status = insufficient_data
    meta: AnalysisMeta
    disclaimer: str = (
        "Informational only, not legal advice. Confirm with the City of Alexandria "
        "Planning & Zoning department before making decisions."
    )


from typing import Literal, Optional
from pydantic import BaseModel, Field

ProviderName = Literal["anthropic", "openai"]


class ChatMessage(BaseModel):
    role: Literal["system", "user", "assistant"]
    content: str


class GenerateRequest(BaseModel):
    messages: list[ChatMessage]
    provider: Optional[ProviderName] = None
    model: Optional[str] = None
    temperature: float = Field(default=0.7, ge=0.0, le=2.0)
    max_tokens: int = Field(default=1024, gt=0)


class TokenUsage(BaseModel):
    input_tokens: int
    output_tokens: int


class GenerateResponse(BaseModel):
    text: str
    provider: ProviderName
    model: str
    usage: TokenUsage
